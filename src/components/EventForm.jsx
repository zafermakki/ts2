
import { useEffect, useRef } from "react";
import FormField from "./FormField";
import ImageUpload from "./ImageUpload";
import FormActions from "./FormActions";
import "../styles/EventForm.css";

const categoryOptions = [
  { value: "conference", label: "Conference" },
  { value: "workshop", label: "Workshop" },
  { value: "meetup", label: "Meetup" },
  { value: "webinar", label: "Webinar" },
  { value: "networking", label: "Networking" },
  { value: "other", label: "Other" },
];

const eventTypeOptions = [
  { value: "online", label: "Online" },
  { value: "in-person", label: "In-Person" },
];

const EventForm = ({
  register,
  formData,
  errors,
  onFieldChange,
  onImageChange,
  onSubmit,
  onReset,
  successMessage,
  submittedEvent,
}) => {
  const successMessageRef = useRef(null);

  useEffect(() => {
    if (successMessage && successMessageRef.current) {
      successMessageRef.current.scrollIntoView({
        behavior: "smooth",
        block: "center",
      });
    }
  }, [successMessage]);

  return (
    <section className="event-form-card">
      <div className="section-heading">
        <div>
          <span className="section-eyebrow">EVENT DETAILS</span>
          <h2>Create your event</h2>
          <p>Fill in the information to create your event.</p>
        </div>

        <span className="required-note">
          <span className="required-mark">*</span> Required fields
        </span>
      </div>

      {/*
        All errors are supplied by React Hook Form,
        using messages generated by Zod.
      */}

      <form onSubmit={onSubmit} noValidate>
        <div className="form-fields">
          <FormField
            label="Event Name"
            name="eventName"
            register={register}
            onFieldChange={onFieldChange}
            placeholder="e.g. Design & Innovation Summit"
            error={errors.eventName?.message}
            required
          />

          <FormField
            label="Description"
            name="description"
            type="textarea"
            register={register}
            onFieldChange={onFieldChange}
            placeholder="Tell people what your event is about..."
            error={errors.description?.message}
            rows={4}
            required
            hint="Provide a short description to help attendees understand your event."
          />

          <div className="form-row">
            <FormField
              label="Event Date"
              name="date"
              type="date"
              register={register}
              onFieldChange={onFieldChange}
              error={errors.date?.message}
              required
            />

            <FormField
              label="Category"
              name="category"
              type="select"
              register={register}
              onFieldChange={onFieldChange}
              options={categoryOptions}
              placeholder="Select category"
              error={errors.category?.message}
              required
            />
          </div>

          <FormField
            label="Event Type"
            name="eventType"
            type="select"
            register={register}
            onFieldChange={onFieldChange}
            options={eventTypeOptions}
            error={errors.eventType?.message}
            required
          />

          {formData.eventType === "online" && (
            <div className="conditional-field">
              <FormField
                label="Meeting URL"
                name="meetingUrl"
                type="url"
                register={register}
                onFieldChange={onFieldChange}
                placeholder="https://meet.example.com/your-event"
                error={errors.meetingUrl?.message}
                required
                hint="Enter the link attendees will use to join the event."
              />
            </div>
          )}

          {formData.eventType === "in-person" && (
            <div className="conditional-field">
              <FormField
                label="Event Location"
                name="location"
                register={register}
                onFieldChange={onFieldChange}
                placeholder="e.g. Damascus International Hotel"
                error={errors.location?.message}
                required
                hint="Enter the venue name or full event address."
              />
            </div>
          )}

          <ImageUpload
            image={formData.coverImage}
            imageName={formData.coverImageName}
            error={errors.coverImage?.message}
            onImageChange={onImageChange}
          />
        </div>

        <FormActions onReset={onReset} />

        {successMessage && submittedEvent && (
          <div
            ref={successMessageRef}
            className="success-message"
            role="status"
            tabIndex={-1}
          >
            <span className="success-icon" aria-hidden="true">
              ✓
            </span>

            <div>
              <strong>{successMessage}</strong>
              <p>
                <span className="submitted-event-name">
                  {submittedEvent.eventName}
                </span>{" "}
                has been submitted successfully.
              </p>
            </div>
          </div>
        )}
      </form>
    </section>
  );
};

export default EventForm;
